#!/usr/bin/env python3
"""
Verifier for exterior_wall_insulation_upgrade task.

Task Requirements:
1. "EWall Construction": U-VALUE = 0.048
2. "Roof Construction": U-VALUE = 0.033
3. Simulation must be run (new .SIM file generated)
4. Project must be saved

Scoring (100 pts):
- Simulation ran during session: 15 pts
- EWall U-VALUE matches 0.048 (±0.003): 30 pts
- EWall modified (keyword present): 5 pts
- Roof U-VALUE matches 0.033 (±0.003): 30 pts
- Roof modified (keyword present): 5 pts
- Project saved: 10 pts
- Proper Syntax (Type=U-Value): 5 pts

Pass threshold: 60 pts AND simulation ran.
"""

import json
import os
import tempfile
import logging

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

# The result file generated by export_result.ps1 inside the Windows VM
RESULT_PATH = "C:\\Users\\Docker\\exterior_wall_insulation_upgrade_result.json"

def verify_exterior_wall_insulation_upgrade(traj, env_info, task_info):
    copy_from_env = env_info.get('copy_from_env')
    if not copy_from_env:
        return {"passed": False, "score": 0, "feedback": "copy_from_env not available"}

    # Load result from container
    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.json')
    try:
        copy_from_env(RESULT_PATH, temp_file.name)
        with open(temp_file.name, 'r') as f:
            result = json.load(f)
    except Exception as e:
        logger.error(f"Failed to read result file: {e}")
        return {
            "passed": False, 
            "score": 0, 
            "feedback": "Failed to retrieve task results. Did you save the project?"
        }
    finally:
        if os.path.exists(temp_file.name):
            os.unlink(temp_file.name)

    # Extract values
    sim_is_new = result.get('sim_file_is_new', False)
    inp_saved = result.get('inp_file_saved', False)
    ewall_u = result.get('ewall_u_value', -1)
    roof_u = result.get('roof_u_value', -1)
    ewall_found = result.get('ewall_found', False)
    roof_found = result.get('roof_found', False)

    # Targets
    target_ewall = 0.048
    target_roof = 0.033
    tolerance = 0.003

    score = 0
    feedback_parts = []

    # Criterion 1: Simulation Ran (15 pts)
    if sim_is_new:
        score += 15
        feedback_parts.append("Simulation ran successfully (+15)")
    else:
        feedback_parts.append("Simulation NOT run during task")

    # Criterion 2: Project Saved (10 pts)
    if inp_saved:
        score += 10
        feedback_parts.append("Project saved (+10)")
    else:
        feedback_parts.append("Project NOT saved")

    # Criterion 3: EWall Construction (35 pts total)
    if ewall_found:
        if ewall_u != -1:
            score += 5 # Found U-Value keyword
            if abs(ewall_u - target_ewall) <= tolerance:
                score += 30
                feedback_parts.append(f"EWall U-Value correct: {ewall_u} (+35)")
            else:
                feedback_parts.append(f"EWall U-Value incorrect: {ewall_u} (Expected {target_ewall})")
        else:
            feedback_parts.append("EWall U-VALUE keyword not found (using Layers?)")
            # If using layers, we might check thermal mass or similar, but task specific U-VALUE
            # Strict mode: 0 points for value if not using U-VALUE method as requested
    else:
        feedback_parts.append("EWall Construction not found in file")

    # Criterion 4: Roof Construction (35 pts total)
    if roof_found:
        if roof_u != -1:
            score += 5 # Found U-Value keyword
            if abs(roof_u - target_roof) <= tolerance:
                score += 30
                feedback_parts.append(f"Roof U-Value correct: {roof_u} (+35)")
            else:
                feedback_parts.append(f"Roof U-Value incorrect: {roof_u} (Expected {target_roof})")
        else:
            feedback_parts.append("Roof U-VALUE keyword not found")
    else:
        feedback_parts.append("Roof Construction not found in file")
        
    # Check syntax/method bonus (5 pts)
    # If both used U-VALUE method
    if ewall_u != -1 and roof_u != -1:
        score += 5
        feedback_parts.append("Correct input syntax used (+5)")

    # Pass Logic
    passed = (score >= 60) and sim_is_new

    return {
        "passed": passed,
        "score": score,
        "feedback": " | ".join(feedback_parts)
    }