#!/bin/bash
# Matomo Setup Script (post_start hook)
# Starts Matomo via Docker, creates database tables, and launches Firefox
#
# Default credentials (set during installation wizard):
#   Super User: admin
#   Password: Admin12345
#   Email: admin@localhost.test

echo "=== Setting up Matomo via Docker ==="

# Configuration
MATOMO_URL="http://localhost/"
ADMIN_USER="admin"
ADMIN_PASS="Admin12345"
ADMIN_EMAIL="admin@localhost.test"

# Function to wait for Matomo to be ready
wait_for_matomo() {
    local timeout=${1:-180}
    local elapsed=0

    echo "Waiting for Matomo to be ready (this may take a few minutes on first run)..."

    while [ $elapsed -lt $timeout ]; do
        # Check if Matomo returns HTTP 200 or 302 (redirect to installer on first run)
        HTTP_CODE=$(curl -s -o /dev/null -w "%{http_code}" "$MATOMO_URL" 2>/dev/null)
        if [ "$HTTP_CODE" = "200" ] || [ "$HTTP_CODE" = "302" ]; then
            echo "Matomo is ready after ${elapsed}s (HTTP $HTTP_CODE)"
            return 0
        fi
        sleep 5
        elapsed=$((elapsed + 5))
        echo "  Waiting... ${elapsed}s (HTTP $HTTP_CODE)"
    done

    echo "WARNING: Matomo readiness check timed out after ${timeout}s"
    return 1
}

# Function to execute SQL
run_sql() {
    docker exec matomo-db mysql -u matomo -pmatomo123 matomo -e "$1"
}

# Copy docker-compose.yml to working directory
echo "Setting up Docker Compose configuration..."
mkdir -p /home/ga/matomo
cp /workspace/config/docker-compose.yml /home/ga/matomo/
chown -R ga:ga /home/ga/matomo

# Start Matomo containers
echo "Starting Matomo Docker containers..."
cd /home/ga/matomo

# Pull images first (better error handling)
docker-compose pull

# Start containers in detached mode
docker-compose up -d

echo "Containers starting..."
docker-compose ps

# Wait for Matomo to be fully ready
wait_for_matomo 180

# Show container status
echo ""
echo "Container status:"
docker-compose ps

# Check if Matomo needs initial setup (installation wizard)
echo ""
echo "Checking Matomo installation status..."

# Wait for database to be fully ready first
echo "Waiting for database to be ready..."
for i in {1..60}; do
    if docker exec matomo-db mysql -u matomo -pmatomo123 matomo -e "SELECT 1" &>/dev/null; then
        echo "Database is ready after ${i}s"
        break
    fi
    sleep 2
done

# Check if config.ini.php exists and has proper setup
CONFIG_EXISTS=$(docker exec matomo-app test -f /var/www/html/config/config.ini.php && echo "yes" || echo "no")
USER_COUNT=$(docker exec matomo-db mysql -u matomo -pmatomo123 matomo -N -e "SELECT COUNT(*) FROM matomo_user" 2>/dev/null || echo "0")

if [ "$CONFIG_EXISTS" = "no" ] || [ "$USER_COUNT" = "0" ]; then
    echo "Matomo installation needed - completing automated setup via database..."

    # Generate a random salt for security
    SALT=$(openssl rand -hex 16)

    # Create config.ini.php inside the container with complete installation flag
    echo "Creating Matomo configuration file..."
    docker exec matomo-app bash -c "cat > /var/www/html/config/config.ini.php << 'CONFIGEOF'
; <?php exit; ?> DO NOT REMOVE THIS LINE
; Matomo configuration file - auto-generated by setup script

[database]
host = \"db\"
username = \"matomo\"
password = \"matomo123\"
dbname = \"matomo\"
tables_prefix = \"matomo_\"
charset = \"utf8mb4\"

[General]
salt = \"${SALT}\"
trusted_hosts[] = \"localhost\"
trusted_hosts[] = \"127.0.0.1\"
enable_browser_archiving_triggering = 1
force_ssl = 0
assume_secure_protocol = 0

[Tracker]
record_statistics = 1

[log]
log_writers[] = \"screen\"
CONFIGEOF"

    # Set proper permissions on config file
    docker exec matomo-app chown www-data:www-data /var/www/html/config/config.ini.php
    docker exec matomo-app chmod 644 /var/www/html/config/config.ini.php

    # Create core database tables directly via SQL
    echo "Creating Matomo database tables via SQL..."

    # Create option table first (needed for version tracking)
    run_sql "CREATE TABLE IF NOT EXISTS matomo_option (
        option_name VARCHAR(191) NOT NULL,
        option_value LONGTEXT NOT NULL,
        autoload TINYINT NOT NULL DEFAULT '1',
        PRIMARY KEY (option_name),
        INDEX autoload(autoload)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Create user table
    run_sql "CREATE TABLE IF NOT EXISTS matomo_user (
        login VARCHAR(100) NOT NULL,
        password VARCHAR(255) NOT NULL,
        email VARCHAR(100) NOT NULL,
        twofactor_secret VARCHAR(40) NOT NULL DEFAULT '',
        superuser_access TINYINT(2) unsigned NOT NULL DEFAULT '0',
        date_registered TIMESTAMP NULL,
        ts_password_modified TIMESTAMP NULL,
        idchange_last_viewed INTEGER UNSIGNED NULL,
        invited_by VARCHAR(100) NULL,
        invite_token VARCHAR(191) NULL,
        invite_link_token VARCHAR(191) NULL,
        invite_expired_at TIMESTAMP NULL,
        invite_accept_at TIMESTAMP NULL,
        ts_changes_shown TIMESTAMP NULL,
        ts_last_seen TIMESTAMP NULL,
        ts_inactivity_notified TIMESTAMP NULL,
        PRIMARY KEY(login),
        UNIQUE INDEX uniq_email (email)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Create site table
    run_sql "CREATE TABLE IF NOT EXISTS matomo_site (
        idsite INTEGER(10) UNSIGNED NOT NULL AUTO_INCREMENT,
        name VARCHAR(90) NOT NULL,
        main_url VARCHAR(255) NOT NULL,
        ts_created TIMESTAMP NULL,
        ecommerce TINYINT DEFAULT 0,
        sitesearch TINYINT DEFAULT 1,
        sitesearch_keyword_parameters TEXT NOT NULL,
        sitesearch_category_parameters TEXT NOT NULL,
        timezone VARCHAR(50) NOT NULL,
        currency CHAR(3) NOT NULL,
        exclude_unknown_urls TINYINT(1) DEFAULT 0,
        excluded_ips TEXT NOT NULL,
        excluded_parameters TEXT NOT NULL,
        excluded_user_agents TEXT NOT NULL,
        excluded_referrers TEXT NOT NULL,
        \`group\` VARCHAR(250) NOT NULL DEFAULT '',
        type VARCHAR(255) NOT NULL DEFAULT 'website',
        keep_url_fragment TINYINT NOT NULL DEFAULT 0,
        creator_login VARCHAR(100) NULL,
        PRIMARY KEY(idsite)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Create access table
    run_sql "CREATE TABLE IF NOT EXISTS matomo_access (
        idaccess INTEGER(10) UNSIGNED NOT NULL AUTO_INCREMENT,
        login VARCHAR(100) NOT NULL,
        idsite INTEGER UNSIGNED NOT NULL,
        access VARCHAR(50) NULL,
        PRIMARY KEY(idaccess),
        INDEX index_loginidsite (login, idsite)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Create goal table (needed for configure_goal task)
    run_sql "CREATE TABLE IF NOT EXISTS matomo_goal (
        idsite INT(11) NOT NULL,
        idgoal INT(11) NOT NULL,
        name VARCHAR(50) NOT NULL,
        description VARCHAR(255) NOT NULL DEFAULT '',
        match_attribute VARCHAR(20) NOT NULL,
        pattern VARCHAR(255) NOT NULL,
        pattern_type VARCHAR(25) NOT NULL,
        case_sensitive TINYINT(4) NOT NULL,
        allow_multiple TINYINT(4) NOT NULL,
        revenue FLOAT NOT NULL,
        deleted TINYINT(4) NOT NULL DEFAULT 0,
        event_value_as_revenue TINYINT(4) NOT NULL DEFAULT 0,
        PRIMARY KEY (idsite, idgoal)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Create a few more essential tables that Matomo expects
    run_sql "CREATE TABLE IF NOT EXISTS matomo_site_setting (
        idsite INTEGER(10) UNSIGNED NOT NULL,
        plugin_name VARCHAR(60) NOT NULL,
        setting_name VARCHAR(255) NOT NULL,
        setting_value LONGTEXT NOT NULL,
        json_encoded TINYINT UNSIGNED NOT NULL DEFAULT 0,
        idsite_setting BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
        PRIMARY KEY (idsite_setting),
        INDEX idsite (idsite, plugin_name)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    run_sql "CREATE TABLE IF NOT EXISTS matomo_plugin_setting (
        plugin_name VARCHAR(60) NOT NULL,
        setting_name VARCHAR(255) NOT NULL,
        setting_value LONGTEXT NOT NULL,
        json_encoded TINYINT UNSIGNED NOT NULL DEFAULT 0,
        user_login VARCHAR(100) NOT NULL DEFAULT '',
        idplugin_setting BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
        PRIMARY KEY (idplugin_setting),
        INDEX plugin_name (plugin_name, user_login)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Create session table
    run_sql "CREATE TABLE IF NOT EXISTS matomo_session (
        id VARCHAR(191) NOT NULL,
        modified INT(10) UNSIGNED,
        lifetime INT(10) UNSIGNED,
        data MEDIUMTEXT,
        PRIMARY KEY (id)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;"

    # Give the database a moment to process
    sleep 2

    # Check if tables were created
    TABLE_COUNT=$(docker exec matomo-db mysql -u matomo -pmatomo123 matomo -N -e "SHOW TABLES LIKE 'matomo_%'" 2>/dev/null | wc -l)
    echo "Database tables created: $TABLE_COUNT"

    # Create superuser via SQL
    echo "Creating admin superuser account via SQL..."

    # Generate password hash using PHP (Matomo uses password_hash with bcrypt)
    PASS_HASH=$(docker exec matomo-app php -r "echo password_hash('${ADMIN_PASS}', PASSWORD_BCRYPT);")

    # Insert user into database
    run_sql "INSERT INTO matomo_user (login, password, email, superuser_access, date_registered, ts_password_modified)
        VALUES ('${ADMIN_USER}', '${PASS_HASH}', '${ADMIN_EMAIL}', 1, NOW(), NOW())
        ON DUPLICATE KEY UPDATE password='${PASS_HASH}', superuser_access=1;" 2>/dev/null || echo "User insertion completed"

    # Create initial website via SQL
    echo "Creating initial website via SQL..."
    run_sql "INSERT INTO matomo_site (name, main_url, ts_created, ecommerce, sitesearch, sitesearch_keyword_parameters, sitesearch_category_parameters, timezone, currency, exclude_unknown_urls, excluded_ips, excluded_parameters, excluded_user_agents, excluded_referrers, \`group\`, type, keep_url_fragment, creator_login)
        VALUES ('Initial Site', 'https://initial-site.example.com', NOW(), 0, 1, '', '', 'Africa/Algiers', 'USD', 0, '', '', '', '', '', 'website', 0, '${ADMIN_USER}')
        ON DUPLICATE KEY UPDATE name='Initial Site';" 2>/dev/null || echo "Site insertion completed"

    # Grant user access to the site
    echo "Granting admin access to initial site..."
    run_sql "INSERT INTO matomo_access (login, idsite, access)
        VALUES ('${ADMIN_USER}', 1, 'admin')
        ON DUPLICATE KEY UPDATE access='admin';" 2>/dev/null || true

    # Mark installation as complete in the option table
    echo "Marking installation as complete..."
    run_sql "INSERT INTO matomo_option (option_name, option_value, autoload) VALUES
        ('install_version', '5', 1),
        ('version_core', '5.0.0', 1),
        ('MatomoInstallationFinished', '1', 1),
        ('UpdateCheck_LastTimeChecked', UNIX_TIMESTAMP(), 0)
        ON DUPLICATE KEY UPDATE option_value=VALUES(option_value);" 2>/dev/null || true

    # Verify the setup
    echo ""
    echo "Verifying installation..."
    USER_COUNT=$(docker exec matomo-db mysql -u matomo -pmatomo123 matomo -N -e "SELECT COUNT(*) FROM matomo_user" 2>/dev/null || echo "0")
    SITE_COUNT=$(docker exec matomo-db mysql -u matomo -pmatomo123 matomo -N -e "SELECT COUNT(*) FROM matomo_site" 2>/dev/null || echo "0")

    echo "  Users created: $USER_COUNT"
    echo "  Sites created: $SITE_COUNT"

    if [ "$USER_COUNT" -gt 0 ] && [ "$SITE_COUNT" -gt 0 ]; then
        echo ""
        echo "SUCCESS: Matomo installation completed automatically!"
        echo "  Login URL: http://localhost/"
        echo "  Username: ${ADMIN_USER}"
        echo "  Password: ${ADMIN_PASS}"
    else
        echo ""
        echo "WARNING: Automated setup may be incomplete."
        echo "  If login page doesn't appear, complete the installation wizard manually."
    fi
else
    echo "Matomo appears to be already configured"
    echo "  Config exists: $CONFIG_EXISTS"
    echo "  User count: $USER_COUNT"
fi

# Set up Firefox profile for user 'ga'
echo "Setting up Firefox profile..."
FIREFOX_PROFILE_DIR="/home/ga/.mozilla/firefox"
sudo -u ga mkdir -p "$FIREFOX_PROFILE_DIR/default-release"

# Create Firefox profiles.ini
cat > "$FIREFOX_PROFILE_DIR/profiles.ini" << 'FFPROFILE'
[Install4F96D1932A9F858E]
Default=default-release
Locked=1

[Profile0]
Name=default-release
IsRelative=1
Path=default-release
Default=1

[General]
StartWithLastProfile=1
Version=2
FFPROFILE
chown ga:ga "$FIREFOX_PROFILE_DIR/profiles.ini"

# Create user.js to configure Firefox (disable first-run dialogs, etc.)
cat > "$FIREFOX_PROFILE_DIR/default-release/user.js" << 'USERJS'
// Disable first-run screens and welcome pages
user_pref("browser.startup.homepage_override.mstone", "ignore");
user_pref("browser.aboutwelcome.enabled", false);
user_pref("browser.rights.3.shown", true);
user_pref("datareporting.policy.dataSubmissionPolicyBypassNotification", true);
user_pref("toolkit.telemetry.reportingpolicy.firstRun", false);
user_pref("browser.shell.checkDefaultBrowser", false);
user_pref("browser.shell.didSkipDefaultBrowserCheckOnFirstRun", true);

// Set homepage to Matomo
user_pref("browser.startup.homepage", "http://localhost/");
user_pref("browser.startup.page", 1);

// Disable update checks
user_pref("app.update.enabled", false);
user_pref("app.update.auto", false);

// Disable password saving prompts
user_pref("signon.rememberSignons", false);
user_pref("signon.autofillForms", false);

// Disable sidebar and other popups
user_pref("sidebar.revamp", false);
user_pref("sidebar.verticalTabs", false);
user_pref("browser.sidebar.dismissed", true);
user_pref("browser.vpn_promo.enabled", false);
user_pref("browser.messaging-system.whatsNewPanel.enabled", false);
user_pref("browser.uitour.enabled", false);
user_pref("browser.newtabpage.activity-stream.asrouter.userprefs.cfr.addons", false);
user_pref("browser.newtabpage.activity-stream.asrouter.userprefs.cfr.features", false);
user_pref("extensions.pocket.enabled", false);
user_pref("identity.fxaccounts.enabled", false);
USERJS
chown ga:ga "$FIREFOX_PROFILE_DIR/default-release/user.js"

# Set ownership of Firefox profile
chown -R ga:ga "$FIREFOX_PROFILE_DIR"

# Create desktop shortcut
mkdir -p /home/ga/Desktop
cat > /home/ga/Desktop/Matomo.desktop << 'DESKTOPEOF'
[Desktop Entry]
Name=Matomo Analytics
Comment=Web Analytics Platform
Exec=firefox http://localhost/
Icon=firefox
StartupNotify=true
Terminal=false
Type=Application
Categories=Office;Development;
DESKTOPEOF
chown ga:ga /home/ga/Desktop/Matomo.desktop
chmod +x /home/ga/Desktop/Matomo.desktop

# Create utility script for database queries
cat > /usr/local/bin/matomo-db-query << 'DBQUERYEOF'
#!/bin/bash
# Execute SQL query against Matomo database (via Docker)
docker exec matomo-db mysql -u matomo -pmatomo123 matomo -e "$1"
DBQUERYEOF
chmod +x /usr/local/bin/matomo-db-query

# Start Firefox for the ga user
echo "Launching Firefox with Matomo..."
su - ga -c "DISPLAY=:1 firefox '$MATOMO_URL' > /tmp/firefox_matomo.log 2>&1 &"

# Wait for Firefox window
sleep 5
FIREFOX_STARTED=false
for i in {1..30}; do
    if DISPLAY=:1 wmctrl -l 2>/dev/null | grep -qi "firefox\|mozilla\|matomo"; then
        FIREFOX_STARTED=true
        echo "Firefox window detected after ${i}s"
        break
    fi
    sleep 1
done

if [ "$FIREFOX_STARTED" = true ]; then
    sleep 2
    # Maximize Firefox window
    WID=$(DISPLAY=:1 wmctrl -l | grep -i "firefox\|mozilla" | head -1 | awk '{print $1}')
    if [ -n "$WID" ]; then
        DISPLAY=:1 wmctrl -ia "$WID" 2>/dev/null || true
        DISPLAY=:1 wmctrl -r :ACTIVE: -b add,maximized_vert,maximized_horz 2>/dev/null || true
    fi
fi

echo ""
echo "=== Final Health Check ==="

# Robust health check - verify Matomo is actually accessible
HEALTH_CHECK_PASSED=false
MAX_HEALTH_RETRIES=30

for i in $(seq 1 $MAX_HEALTH_RETRIES); do
    # Check Docker containers are running
    CONTAINERS_RUNNING=$(docker ps --format "{{.Names}}" 2>/dev/null | grep -c "matomo" || echo "0")
    if [ "$CONTAINERS_RUNNING" -lt 2 ]; then
        echo "  Health check $i/$MAX_HEALTH_RETRIES: Docker containers not running ($CONTAINERS_RUNNING/2), restarting..."
        cd /home/ga/matomo && docker-compose up -d 2>/dev/null
        sleep 10
        continue
    fi

    # Check HTTP response from Matomo
    HTTP_CODE=$(curl -s -o /dev/null -w "%{http_code}" "http://localhost/" 2>/dev/null)
    if [ "$HTTP_CODE" = "200" ] || [ "$HTTP_CODE" = "302" ]; then
        # Verify page content contains Matomo (not error page)
        PAGE_CONTENT=$(curl -s "http://localhost/" 2>/dev/null | head -100)
        if echo "$PAGE_CONTENT" | grep -qi "matomo\|piwik\|installation\|sign in\|login"; then
            echo "  Health check $i/$MAX_HEALTH_RETRIES: Matomo accessible (HTTP $HTTP_CODE, content verified)"
            HEALTH_CHECK_PASSED=true
            break
        else
            echo "  Health check $i/$MAX_HEALTH_RETRIES: HTTP $HTTP_CODE but content not recognized"
        fi
    else
        echo "  Health check $i/$MAX_HEALTH_RETRIES: HTTP $HTTP_CODE (waiting...)"
    fi

    sleep 5
done

if [ "$HEALTH_CHECK_PASSED" = true ]; then
    echo ""
    echo "=== Matomo Setup Complete ==="
    echo ""
    echo "Matomo is running at: http://localhost/"
    echo ""
    echo "Login credentials:"
    echo "  Username: ${ADMIN_USER}"
    echo "  Password: ${ADMIN_PASS}"
else
    echo ""
    echo "=== WARNING: Matomo Health Check Failed ==="
    echo ""
    echo "Matomo may not be fully accessible. Common issues:"
    echo "  - Docker Hub rate limiting (wait and retry)"
    echo "  - Container startup delay (containers may still be initializing)"
    echo ""
    echo "Troubleshooting commands:"
    echo "  docker ps                                    # Check running containers"
    echo "  docker-compose -f /home/ga/matomo/docker-compose.yml logs  # View logs"
    echo "  docker-compose -f /home/ga/matomo/docker-compose.yml up -d # Restart"
fi

echo ""
echo "Database access (via Docker):"
echo "  matomo-db-query \"SELECT COUNT(*) FROM matomo_site\""
echo ""
echo "Docker commands:"
echo "  docker-compose -f /home/ga/matomo/docker-compose.yml logs -f"
echo "  docker-compose -f /home/ga/matomo/docker-compose.yml ps"
echo ""
