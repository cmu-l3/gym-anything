def get_technician_key():
    # Helper to get key using the existing login script in the environment
    # or assuming default if already generated
    try:
        from sdp_login import login_and_get_key
        return login_and_get_key()
    except ImportError:
        # Fallback: Try to read from file if generated by task_utils
        return os.popen("bash -c 'source /workspace/scripts/task_utils.sh; get_sdp_api_key_from_db'").read().strip()

def create_requester(name, email):
    headers = {"TECHNICIAN_KEY": TECHNICIAN_KEY}
    data = {
        "requester": {
            "name": name,
            "email_id": email,
            "is_vipuser": False
        }
    }
    input_data = {"input_data": data}
    
    # Check if exists first
    search_url = f"{API_URL}/requesters?input_data={json.dumps({'list_info': {'search_fields': {'email_id': email}}})}"
    try:
        r = requests.get(search_url, headers=headers, verify=False)
        if r.status_code == 200 and r.json().get("requesters"):
            print(f"Requester {name} already exists.")
            return r.json()["requesters"][0]["id"]
    except Exception as e:
        print(f"Search failed: {e}")

    # Create
    url = f"{API_URL}/requesters"
    files = {'input_data': (None, json.dumps(data))} 
    # Note: SDP API v3 uses multipart/form-data for input_data or query param
    # Using simple post with data payload often works or input_data param
    
    try:
        r = requests.post(url, headers=headers, data={'input_data': json.dumps(data)}, verify=False)
        if r.status_code in [200, 201]:
            resp = r.json()
            if resp.get("response_status", {}).get("status") == "success":
                user_id = resp["requester"]["id"]
                print(f"Created requester {name}: {user_id}")
                return user_id
            else:
                print(f"Failed to create requester {name}: {resp}")
        else:
            print(f"HTTP Error creating requester: {r.text}")
    except Exception as e:
        print(f"Exception creating requester: {e}")
    return None

def create_request(subject, requester_id):
    if not requester_id:
        return
        
    headers = {"TECHNICIAN_KEY": TECHNICIAN_KEY}
    data = {
        "request": {
            "subject": subject,
            "requester": {"id": requester_id},
            "priority": {"name": "Medium"},
            "status": {"name": "Open"}
        }
    }
    
    url = f"{API_URL}/requests"
    try:
        r = requests.post(url, headers=headers, data={'input_data': json.dumps(data)}, verify=False)
        if r.status_code in [200, 201]:
            resp = r.json()
            if resp.get("request"):
                print(f"Created request '{subject}': {resp['request']['id']}")
                return resp['request']['id']
    except Exception as e:
        print(f"Exception creating request: {e}")

def main():
    global TECHNICIAN_KEY
    # Generate/Get API Key
    # We'll try to get it from the DB helper first
    TECHNICIAN_KEY = os.popen("bash -c 'source /workspace/scripts/task_utils.sh; get_sdp_api_key_from_db'").read().strip()
    
    if not TECHNICIAN_KEY:
        print("Could not retrieve API Key from DB. Trying web generation...")
        # Trigger the python login script provided by environment
        os.system("python3 /tmp/sdp_login.py")
        TECHNICIAN_KEY = os.popen("bash -c 'source /workspace/scripts/task_utils.sh; get_sdp_api_key_from_db'").read().strip()

    if not TECHNICIAN_KEY:
        print("FATAL: Failed to get API Key.")
        sys.exit(1)

    print(f"Using API Key: {TECHNICIAN_KEY[:5]}...")

    # Create Secondary User (To be merged/deleted)
    old_user_id = create_requester("Cameron Howe", "cameron@mutiny.com")
    
    # Create Primary User (To keep)
    new_user_id = create_requester("C. Howe", "chowe@mutiny.com")
    
    # Create Ticket assigned to OLD user
    if old_user_id:
        create_request("BIOS firmware update for Mutiny mainframes", old_user_id)
        
    # Save IDs to tmp for verification reference (optional, verifier will query by name)
    with open("/tmp/initial_ids.json", "w") as f:
        json.dump({
            "old_user_id": old_user_id,
            "new_user_id": new_user_id
        }, f)

if __name__ == "__main__":
    main()
PYEOF

