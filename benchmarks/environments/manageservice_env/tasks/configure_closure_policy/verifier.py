#!/usr/bin/env python3
"""
Verifier for configure_closure_policy task.

Checks if:
1. Request closing rules enforce mandatory fields (Category, Priority, Resolution).
2. Auto-close is enabled and set to 3 days.

It relies on a JSON result file generated by `export_result.sh` which runs
inside the container and interacts with the SDP API/DB.
"""

import json
import os
import tempfile

def verify_configure_closure_policy(traj, env_info, task_info):
    copy_from_env = env_info.get('copy_from_env')
    if not copy_from_env:
        return {"passed": False, "score": 0, "feedback": "Copy function not available"}

    # Retrieve the result JSON from the container
    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.json')
    try:
        copy_from_env("/tmp/task_result.json", temp_file.name)
        with open(temp_file.name, 'r') as f:
            result = json.load(f)
    except Exception as e:
        return {
            "passed": False, 
            "score": 0, 
            "feedback": f"Failed to retrieve or parse verification results: {e}"
        }
    finally:
        if os.path.exists(temp_file.name):
            os.unlink(temp_file.name)

    score = 0
    feedback = []
    
    # Check for script errors
    if result.get("error"):
        feedback.append(f"Verification script warning: {result['error']}")

    # 1. Behavioral Policy Test (40 pts)
    # Did the system BLOCK closing a request when fields were missing?
    if result.get("policy_active_negative_test"):
        score += 40
        feedback.append("Success: System correctly blocked closing invalid requests.")
        
        # Bonus check: detected specific missing fields?
        detected = result.get("mandatory_fields_detected", [])
        if detected:
            feedback.append(f"Validation correctly flagged missing: {', '.join(detected)}")
    else:
        feedback.append("Fail: System allowed closing a request without mandatory fields (Policy not active).")

    # 2. Positive Test (20 pts)
    # Did the system ALLOW closing when fields were provided?
    if result.get("policy_valid_positive_test"):
        score += 20
        feedback.append("Success: System allowed closing valid requests.")
    else:
        feedback.append("Fail: Could not close request even with fields filled (Configuration might be broken).")

    # 3. Auto-Close Enabled (20 pts)
    if result.get("auto_close_enabled"):
        score += 20
        feedback.append("Success: Auto-close feature is enabled.")
    else:
        feedback.append("Fail: Auto-close feature is disabled.")

    # 4. Auto-Close Duration (20 pts)
    days = result.get("auto_close_days", -1)
    if days == 3:
        score += 20
        feedback.append("Success: Auto-close duration is set to 3 days.")
    else:
        feedback.append(f"Fail: Auto-close duration is {days} (expected 3).")

    # Final check
    passed = (score >= 60 and result.get("policy_active_negative_test"))
    
    return {
        "passed": passed,
        "score": score,
        "feedback": " ".join(feedback)
    }