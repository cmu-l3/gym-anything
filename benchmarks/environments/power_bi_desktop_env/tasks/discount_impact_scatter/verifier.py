#!/usr/bin/env python3
"""
Verifier for discount_impact_scatter task.

Scoring (100 points total):
1. File Saved (10 pts): .pbix exists and created during task.
2. Page Name (15 pts): Contains "Discount Impact".
3. Visuals Present (45 pts):
   - Scatter Chart (15 pts)
   - Line Chart (15 pts)
   - Card (15 pts)
4. DAX Measures (30 pts):
   - Total_Profit (15 pts)
   - Profit_Ratio (15 pts)

Pass threshold: 70 points
"""

import json
import os
import tempfile
import logging

logger = logging.getLogger(__name__)

def verify_discount_impact_scatter(traj, env_info, task_info):
    """
    Verifies the Power BI Discount Impact Scatter task.
    Requires 'copy_from_env' to retrieve the analysis JSON generated by export_result.ps1.
    """
    
    # 1. Setup and retrieve result file
    copy_from_env = env_info.get('copy_from_env')
    if not copy_from_env:
        return {
            "passed": False, 
            "score": 0, 
            "feedback": "Critical Error: copy_from_env function not available."
        }

    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.json')
    temp_file.close()
    
    try:
        # Path inside the Windows VM
        vm_path = r"C:\Users\Docker\Desktop\discount_impact_result.json"
        copy_from_env(vm_path, temp_file.name)
        
        with open(temp_file.name, 'r', encoding='utf-8') as f:
            result = json.load(f)
            
    except Exception as e:
        return {
            "passed": False, 
            "score": 0, 
            "feedback": f"Failed to retrieve or parse result file from agent: {str(e)}"
        }
    finally:
        if os.path.exists(temp_file.name):
            try:
                os.unlink(temp_file.name)
            except:
                pass

    # 2. Scoring Logic
    score = 0
    feedback_parts = []
    
    # Criterion 1: File Existence & Timestamp (10 pts)
    if result.get("file_exists", False) and result.get("file_created_during_task", False):
        score += 10
        feedback_parts.append("✅ Report saved.")
    elif result.get("file_exists", False):
        score += 5
        feedback_parts.append("⚠️ Report exists but timestamp verification failed (possible pre-existing file).")
    else:
        feedback_parts.append("❌ Report file not found.")
        # If file missing, early return usually, but we check structure just in case
        return {"passed": False, "score": 0, "feedback": "Report file not found on Desktop."}

    # Criterion 2: Page Name (15 pts)
    # Flexible matching for "Discount Impact"
    page_names = result.get("page_names", [])
    if any("discount impact" in p.lower() for p in page_names):
        score += 15
        feedback_parts.append("✅ Page named 'Discount Impact' found.")
    else:
        feedback_parts.append(f"❌ Page 'Discount Impact' not found. Found: {page_names}")

    # Criterion 3: Visual Types (45 pts total)
    visuals = result.get("visual_types", [])
    layout_dump = result.get("full_layout_search", "")
    
    # Check Scatter Chart
    if "scatterChart" in visuals or "scatterChart" in layout_dump:
        score += 15
        feedback_parts.append("✅ Scatter chart found.")
    else:
        feedback_parts.append("❌ Scatter chart missing.")
        
    # Check Line Chart
    if "lineChart" in visuals or "lineChart" in layout_dump:
        score += 15
        feedback_parts.append("✅ Line chart found.")
    else:
        feedback_parts.append("❌ Line chart missing.")
        
    # Check Card
    if "card" in visuals or "card" in layout_dump:
        score += 15
        feedback_parts.append("✅ Card visual found.")
    else:
        feedback_parts.append("❌ Card visual missing.")

    # Criterion 4: DAX Measures (30 pts total)
    measures = result.get("measures_found", [])
    
    if "Total_Profit" in measures:
        score += 15
        feedback_parts.append("✅ Measure 'Total_Profit' found.")
    else:
        feedback_parts.append("❌ Measure 'Total_Profit' not detected in data model.")
        
    if "Profit_Ratio" in measures:
        score += 15
        feedback_parts.append("✅ Measure 'Profit_Ratio' found.")
    else:
        feedback_parts.append("❌ Measure 'Profit_Ratio' not detected in data model.")

    # 3. Final Assessment
    passed = score >= 70
    feedback_str = f"Score: {score}/100. " + " ".join(feedback_parts)
    
    return {
        "passed": passed,
        "score": score,
        "feedback": feedback_str
    }