#!/bin/bash
# set -euo pipefail

source /workspace/scripts/task_utils.sh

echo "=== Setting up Wrap Generated gRPC Client Task ==="

WORKSPACE_DIR="/home/ga/workspace/grpc_wrapper_task"
sudo -u ga mkdir -p "$WORKSPACE_DIR"
sudo -u ga mkdir -p "$WORKSPACE_DIR/generated"
sudo -u ga mkdir -p "$WORKSPACE_DIR/protos"
sudo -u ga mkdir -p "$WORKSPACE_DIR/src"

# Install grpcio and grpcio-tools if not present
echo "Ensuring gRPC tools are installed..."
sudo -u ga pip3 install --quiet grpcio grpcio-tools 2>/dev/null || true

# Create the proto file
cat > "$WORKSPACE_DIR/protos/user_service.proto" << 'EOF'
syntax = "proto3";

package userservice;

service UserService {
  rpc CreateUser (CreateUserRequest) returns (CreateUserResponse);
  rpc GetUser (GetUserRequest) returns (GetUserResponse);
}

message CreateUserRequest {
  string name = 1;
  int32 age = 2;
  string email = 3;
}

message CreateUserResponse {
  string user_id = 1;
  string status = 2;
}

message GetUserRequest {
  string user_id = 1;
}

message GetUserResponse {
  string user_id = 1;
  string name = 2;
  int32 age = 3;
  string email = 4;
}
EOF

# Generate Python gRPC code
echo "Generating gRPC Python code..."
cd "$WORKSPACE_DIR"
sudo -u ga python3 -m grpc_tools.protoc \
    -I./protos \
    --python_out=./generated \
    --grpc_python_out=./generated \
    ./protos/user_service.proto 2>/dev/null || echo "⚠️ Proto generation had warnings (expected)"

# Create __init__.py files
touch "$WORKSPACE_DIR/generated/__init__.py"
touch "$WORKSPACE_DIR/src/__init__.py"

# Create README with warning
cat > "$WORKSPACE_DIR/README.md" << 'EOF'
# User Service gRPC Project

## ⚠️ IMPORTANT: Generated Code Warning

**DO NOT EDIT FILES IN `generated/` DIRECTORY DIRECTLY**

Files in `generated/` are auto-generated by `protoc` compiler:
- `user_service_pb2.py` - Message classes
- `user_service_pb2_grpc.py` - Service stubs

