#!/usr/bin/env python3
"""
Verifier for insert_images task.
Analyzes the JSON result generated by export_result.sh inside the container.
"""

import json
import tempfile
import os
import logging

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def verify_insert_images(traj, env_info, task_info):
    """
    Verify that images were inserted onto the correct slides.
    
    Criteria:
    1. File exists and was modified (10 pts)
    2. Slide count is correct (5 pts)
    3. Slide 2 has an image (25 pts)
    4. Slide 3 has an image (25 pts)
    5. Slide 4 has an image (25 pts)
    6. Slides 1 and 5 do NOT have images (10 pts)
    """
    copy_from_env = env_info.get('copy_from_env')
    if not copy_from_env:
        return {"passed": False, "score": 0, "feedback": "Copy function not available"}

    # Copy result JSON from container
    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.json')
    try:
        copy_from_env("/tmp/task_result.json", temp_file.name)
        with open(temp_file.name, 'r') as f:
            result = json.load(f)
    except Exception as e:
        return {"passed": False, "score": 0, "feedback": f"Failed to read result: {e}"}
    finally:
        if os.path.exists(temp_file.name):
            os.unlink(temp_file.name)

    # Check for critical failures
    if result.get("critical_failure", False) or result.get("error"):
        return {
            "passed": False, 
            "score": 0, 
            "feedback": f"Analysis failed: {result.get('error', 'Unknown error')}"
        }

    score = 0
    feedback_parts = []
    
    # 1. File existence and modification (10 pts)
    if result.get("file_exists", False):
        if result.get("file_modified_during_task", False):
            score += 10
            feedback_parts.append("✅ File saved")
        else:
            feedback_parts.append("⚠️ File exists but not modified (did you save?)")
    else:
        feedback_parts.append("❌ File not found")
        return {"passed": False, "score": 0, "feedback": "Presentation file not found"}

    # 2. Slide count (5 pts)
    slide_count = result.get("slide_count", 0)
    if slide_count == 5:
        score += 5
    else:
        feedback_parts.append(f"⚠️ Incorrect slide count: {slide_count} (expected 5)")

    # Slides image check
    slides_with_images = result.get("slides_with_images", {})
    # JSON keys are strings, indices are 0-based
    # Target slides: 2, 3, 4 (indices 1, 2, 3)
    # Avoid slides: 1, 5 (indices 0, 4)

    # 3. Slide 2 (25 pts)
    if slides_with_images.get("1", False):
        score += 25
        feedback_parts.append("✅ Slide 2 image inserted")
    else:
        feedback_parts.append("❌ Slide 2 missing image")

    # 4. Slide 3 (25 pts)
    if slides_with_images.get("2", False):
        score += 25
        feedback_parts.append("✅ Slide 3 image inserted")
    else:
        feedback_parts.append("❌ Slide 3 missing image")

    # 5. Slide 4 (25 pts)
    if slides_with_images.get("3", False):
        score += 25
        feedback_parts.append("✅ Slide 4 image inserted")
    else:
        feedback_parts.append("❌ Slide 4 missing image")

    # 6. Negative check (10 pts)
    s1_clean = not slides_with_images.get("0", False)
    s5_clean = not slides_with_images.get("4", False)
    
    if s1_clean and s5_clean:
        score += 10
    else:
        feedback_parts.append("⚠️ Images inserted on wrong slides (1 or 5)")

    pass_threshold = task_info.get("metadata", {}).get("pass_threshold", 60)
    passed = score >= pass_threshold
    
    return {
        "passed": passed,
        "score": score,
        "feedback": " | ".join(feedback_parts)
    }