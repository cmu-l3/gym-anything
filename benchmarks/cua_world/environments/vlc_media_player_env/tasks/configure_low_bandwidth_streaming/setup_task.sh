#!/bin/bash
# set -euo pipefail

source /workspace/scripts/task_utils.sh

echo "=== Setting up Configure Low-Bandwidth Streaming Task ==="

# Kill any existing VLC instances
kill_vlc ga

sleep 1

# Ensure VLC config directory exists
VLC_CONFIG_DIR="/home/ga/.config/vlc"
mkdir -p "$VLC_CONFIG_DIR"
chown -R ga:ga "$VLC_CONFIG_DIR"

# Backup existing config if present
if [ -f "$VLC_CONFIG_DIR/vlcrc" ]; then
    echo "Backing up existing VLC config..."
    cp "$VLC_CONFIG_DIR/vlcrc" "$VLC_CONFIG_DIR/vlcrc.backup.$(date +%s)"
fi

# Create a fresh vlcrc with default network-caching (1000ms)
echo "Creating default VLC config with network-caching=1000ms..."
cat > "$VLC_CONFIG_DIR/vlcrc" << 'EOF'
# VLC media player configuration file
# This file is automatically generated

[core]
# Network caching (default: 1000ms)
network-caching=1000

# Other caching defaults
file-caching=300
disc-caching=300
live-caching=300

# Disable update check and tips
qt-privacy-ask=0
qt-updates-notif=0
EOF

chown ga:ga "$VLC_CONFIG_DIR/vlcrc"
chmod 644 "$VLC_CONFIG_DIR/vlcrc"

echo "✓ VLC config initialized with network-caching=1000ms"

# Create a test stream URL file for optional testing
echo "Creating test stream reference..."
STREAM_URL="http://commondatastorage.googleapis.com/gtv-videos-bucket/sample/BigBuckBunny.mp4"
echo "$STREAM_URL" > /home/ga/test_stream_url.txt
chown ga:ga /home/ga/test_stream_url.txt

# Launch VLC without any media
echo "Launching VLC..."
su - ga -c "DISPLAY=:1 LIBVA_DRIVER_NAME='' VDPAU_DRIVER='' vlc --avcodec-hw=none --no-video-title-show > /tmp/vlc_low_bandwidth_task.log 2>&1 &"

if ! wait_for_process "vlc" 15; then
    echo "ERROR: VLC failed to start"
    cat /tmp/vlc_low_bandwidth_task.log
    exit 1
fi

if ! wait_for_window "VLC media player" 20; then
    echo "ERROR: VLC window did not appear"
    exit 1
fi

# Click on center of the screen to select current desktop (should be done in all tasks), and then focus window.
echo "Selecting desktop..."
su - ga -c "DISPLAY=:1 xdotool mousemove 600 600 click 1" || true
sleep 1

# Focus VLC window
wid=$(get_vlc_window_id)
if [ -n "$wid" ]; then
    focus_window "$wid"
fi

# Give VLC a moment to fully initialize
sleep 2

echo "=== Configure Low-Bandwidth Streaming Task Setup Complete ==="
echo ""
echo "📝 Task Instructions:"
echo "=========================================="
echo "GOAL: Configure VLC for smooth streaming on slow connections"
echo ""
echo "STEPS:"
echo "  1. Open Preferences:"
echo "     - Go to Tools → Preferences (or press Ctrl+P)"
echo ""
echo "  2. Switch to Advanced mode:"
echo "     - Look for 'Show settings' section at bottom-left"
echo "     - Click the 'All' radio button (not 'Simple')"
echo ""
echo "  3. Navigate to Network settings:"
echo "     - In the left sidebar tree, expand 'Input / Codecs'"
echo "     - Click on 'Network' (or search for 'network caching')"
echo ""
echo "  4. Increase network cache:"
echo "     - Find the 'Network caching (ms)' field"
echo "     - Current value: 1000"
echo "     - Change to: 5000 or higher"
echo ""
echo "  5. Save settings:"
echo "     - Click the 'Save' button at bottom-right"
echo "     - Close preferences window"
echo ""
echo "CONTEXT: This increases buffering to prevent constant pausing"
echo "         on slow internet connections (rural, travel, etc.)"
echo ""
echo "TEST (optional): Open test_stream_url.txt in home directory"
echo "=========================================="