#!/bin/bash
# set -euo pipefail

source /workspace/scripts/task_utils.sh

echo "=== Setting up Troubleshoot Video Output Task ==="

# Kill any existing VLC instances
kill_vlc ga

sleep 1

# Ensure VLC config directory exists
mkdir -p /home/ga/.config/vlc
chown -R ga:ga /home/ga/.config/vlc

# Create test video if it doesn't exist (high-res, high-fps to make tearing visible)
TEST_VIDEO="/home/ga/Videos/test_playback.mp4"
if [ ! -f "$TEST_VIDEO" ]; then
    echo "Creating test video for playback testing..."
    su - ga -c "ffmpeg -f lavfi -i testsrc=duration=30:size=1920x1080:rate=60 \
        -vf \"drawtext=text='Screen Tearing Test - Configure Output Module':fontsize=36:fontcolor=white:x=(w-text_w)/2:y=(h-text_h)/2\" \
        -c:v libx264 -preset fast -crf 18 \
        '$TEST_VIDEO' 2>/dev/null" || {
        echo "WARNING: Could not create test video, using existing sample"
        TEST_VIDEO="/home/ga/Videos/sample_video.mp4"
    }
fi

# Backup existing vlcrc if it exists
VLC_RC="/home/ga/.config/vlc/vlcrc"
if [ -f "$VLC_RC" ]; then
    cp "$VLC_RC" "$VLC_RC.backup.$(date +%s)"
fi

# Create fresh vlcrc with automatic video output (simulating the problematic state)
echo "Resetting VLC config to automatic video output (problematic state)..."
cat > "$VLC_RC" << 'EOF'
# VLC configuration file
# This file is automatically generated

[core]
# Disable tips and privacy dialogs
qt-privacy-ask=0
qt-continue=0
qt-updates-notif=0

[video]
# Video output set to automatic (causing the "problem")
# This simulates the state after a driver update
vout=auto

# Snapshot settings
snapshot-path=/home/ga/Pictures/vlc
snapshot-format=png

[audio]
# Audio settings
audio-volume=256

[qt]
# Qt interface settings
qt-privacy-ask=0
qt-video-autoresize=1
EOF

chown ga:ga "$VLC_RC"
chmod 644 "$VLC_RC"

echo "VLC config reset to automatic video output"

# Launch VLC with the test video
echo "Launching VLC..."
su - ga -c "DISPLAY=:1 LIBVA_DRIVER_NAME='' VDPAU_DRIVER='' vlc --avcodec-hw=none --no-video-title-show --loop '$TEST_VIDEO' > /tmp/vlc_output_task.log 2>&1 &"

if ! wait_for_process "vlc" 15; then
    echo "ERROR: VLC failed to start"
    cat /tmp/vlc_output_task.log
    exit 1
fi

if ! wait_for_window "VLC media player" 20; then
    echo "ERROR: VLC window did not appear"
    exit 1
fi

# Click on center of the screen to select current desktop (should be done in all tasks), and then focus window.
echo "Selecting desktop..."
su - ga -c "DISPLAY=:1 xdotool mousemove 600 600 click 1" || true
sleep 1

# Focus VLC window
wid=$(get_vlc_window_id)
if [ -n "$wid" ]; then
    focus_window "$wid"
fi

# Let video play for a moment to "demonstrate" the tearing issue
sleep 2

echo "=== Troubleshoot Video Output Task Setup Complete ==="
echo "📝 Instructions:"
echo "  1. VLC is experiencing screen tearing due to automatic video output"
echo "  2. Configure VLC to use OpenGL video output module:"
echo "     - Open Tools → Preferences (Ctrl+P)"
echo "     - Click 'All' at bottom-left to show all settings"
echo "     - Navigate to: Video → Output modules"
echo "     - Find 'Video output module' dropdown"
echo "     - Select 'OpenGL video output' (or similar OpenGL option)"
echo "     - Click 'Save' button"
echo "  3. The configuration must be saved to vlcrc file"
echo ""
echo "  Alternative path: Tools → Preferences → Show settings: All → Video → Output modules → Video output module"