#!/usr/bin/env python3
"""
Verifier for budget_variance_waterfall task.

Scoring (100 points total):
1. File saved & valid (10 pts)
2. Data Import (15 pts): Both 'sales_data' and 'category_budget' tables found
3. Page Name (10 pts): Page named "Variance Analysis"
4. Measures (25 pts): 
   - Total_Sales (10)
   - Budget_Amount (10)
   - Budget_Variance (5)
5. Visuals (40 pts):
   - Waterfall Chart (25)
   - Card Visual (15)

Pass Threshold: 65 points
"""

import json
import os
import tempfile
import logging

logger = logging.getLogger(__name__)

def verify_budget_variance_waterfall(traj, env_info, task_info):
    """Verify the Power BI variance report."""
    
    # 1. Setup access to VM result file
    copy_from_env = env_info.get('copy_from_env')
    if not copy_from_env:
        return {"passed": False, "score": 0, "feedback": "System Error: copy_from_env not available"}

    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.json')
    temp_file.close()
    
    try:
        # Copy result JSON generated by PowerShell script
        copy_from_env("C:/Users/Docker/Desktop/variance_result.json", temp_file.name)
        
        with open(temp_file.name, 'r', encoding='utf-8-sig', errors='replace') as f:
            result = json.load(f)
            
    except Exception as e:
        logger.error(f"Failed to read result: {e}")
        return {"passed": False, "score": 0, "feedback": f"Could not verify task result: {e}"}
    finally:
        if os.path.exists(temp_file.name):
            os.unlink(temp_file.name)

    # 2. Scoring Logic
    score = 0
    feedback_parts = []
    
    # Criterion 1: File Existence & Anti-gaming (10 pts)
    if result.get('file_exists') and result.get('file_created_during_task'):
        score += 10
        feedback_parts.append("File saved successfully.")
    elif result.get('file_exists'):
        score += 5
        feedback_parts.append("File exists but timestamp check failed (pre-existing?).")
    else:
        feedback_parts.append("Report file not found.")
        return {"passed": False, "score": 0, "feedback": "No report file found on Desktop."}

    # Criterion 2: Data Import (15 pts)
    found_tables = result.get('found_tables', [])
    if 'sales_data' in found_tables and 'category_budget' in found_tables:
        score += 15
        feedback_parts.append("Both data tables imported.")
    elif 'category_budget' in found_tables:
        score += 10
        feedback_parts.append("Budget table imported, but Sales table check failed.")
    else:
        feedback_parts.append(f"Missing tables (Found: {found_tables}).")

    # Criterion 3: Page Name (10 pts)
    page_names = [p.lower() for p in result.get('page_names', [])]
    if any("variance" in p for p in page_names):
        score += 10
        feedback_parts.append("Page 'Variance Analysis' found.")
    else:
        feedback_parts.append(f"Page name incorrect (Found: {result.get('page_names')}).")

    # Criterion 4: DAX Measures (25 pts)
    measures = result.get('found_measures', [])
    m_score = 0
    if "Total_Sales" in measures: m_score += 10
    if "Budget_Amount" in measures: m_score += 10
    if "Budget_Variance" in measures: m_score += 5
    score += m_score
    if m_score == 25:
        feedback_parts.append("All DAX measures created.")
    elif m_score > 0:
        feedback_parts.append(f"Some DAX measures missing (Found: {measures}).")
    else:
        feedback_parts.append("No required DAX measures found.")

    # Criterion 5: Visuals (40 pts)
    visuals = result.get('visual_types', [])
    v_score = 0
    
    # Check for Waterfall (waterfallChart)
    has_waterfall = any('waterfall' in v.lower() for v in visuals)
    if has_waterfall:
        v_score += 25
        feedback_parts.append("Waterfall chart present.")
    else:
        feedback_parts.append("Waterfall chart missing.")

    # Check for Card (card)
    has_card = any('card' in v.lower() for v in visuals)
    if has_card:
        v_score += 15
        feedback_parts.append("Card visual present.")
    else:
        feedback_parts.append("Card visual missing.")
        
    score += v_score

    # Final result
    passed = score >= 65
    
    return {
        "passed": passed,
        "score": score,
        "feedback": " ".join(feedback_parts),
        "details": result
    }