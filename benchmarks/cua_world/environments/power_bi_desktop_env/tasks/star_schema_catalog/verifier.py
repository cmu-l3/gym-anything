#!/usr/bin/env python3
"""
Verifier for star_schema_catalog task.

Criteria (100 pts total):
1. File Saved (10 pts): .pbix exists and created during task.
2. Tables (15 pts): Data model contains products, reps, sales_facts.
3. Relationships (20 pts): At least 2 relationships created.
4. Calculated Column (20 pts): 'Profit_Per_Unit' exists in 'products' as calculated column.
5. Scatter Chart (20 pts): 'scatterChart' visual present.
6. Treemap (15 pts): 'treemap' visual present.
"""

import json
import os
import tempfile
import logging

logger = logging.getLogger(__name__)

def verify_star_schema_catalog(traj, env_info, task_info):
    """Verify Power BI Star Schema task results."""
    
    # 1. Setup access to file from VM
    copy_from_env = env_info.get('copy_from_env')
    if not copy_from_env:
        return {"passed": False, "score": 0, "feedback": "Environment access failed (copy_from_env missing)"}

    temp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.json')
    temp_file.close()
    
    try:
        # Copy result JSON generated by export_result.ps1
        copy_from_env("C:/Users/Docker/Desktop/catalog_analysis_result.json", temp_file.name)
        
        with open(temp_file.name, 'r') as f:
            result = json.load(f)
    except Exception as e:
        logger.error(f"Failed to load result: {e}")
        return {
            "passed": False, 
            "score": 0, 
            "feedback": "Failed to retrieve verification data from environment. Ensure file was saved."
        }
    finally:
        if os.path.exists(temp_file.name):
            os.unlink(temp_file.name)

    # 2. Score Calculation
    score = 0
    feedback = []
    
    # Criterion 1: File Existence & Validity (10 pts)
    if result.get('file_exists') and result.get('file_created_after_task'):
        score += 10
        feedback.append("✅ Report saved successfully.")
    else:
        feedback.append("❌ Report file missing or not created during this session.")

    # Criterion 2: Data Model Tables (15 pts)
    tables = [t.lower() for t in result.get('tables_found', [])]
    required_tables = ['products', 'reps', 'sales_facts']
    tables_found_count = sum(1 for t in required_tables if any(rt in t for rt in required_tables))
    
    if tables_found_count >= 3:
        score += 15
        feedback.append("✅ All 3 required tables imported.")
    elif tables_found_count > 0:
        score += 5 * tables_found_count
        feedback.append(f"⚠️ Only {tables_found_count}/3 tables found.")
    else:
        feedback.append("❌ No required tables found in data model.")

    # Criterion 3: Relationships (20 pts)
    # Expecting at least 2 relationships for a star schema of 3 tables
    rels = result.get('relationships_count', 0)
    if rels >= 2:
        score += 20
        feedback.append(f"✅ Relationships established (Count: {rels}).")
    elif rels == 1:
        score += 10
        feedback.append("⚠️ Only 1 relationship found (need 2).")
    else:
        feedback.append("❌ No relationships found in data model.")

    # Criterion 4: Calculated Column (20 pts)
    if result.get('calculated_column_found'):
        score += 20
        feedback.append("✅ Calculated column 'Profit_Per_Unit' found.")
    else:
        feedback.append("❌ Calculated column 'Profit_Per_Unit' not found in products table.")

    # Criterion 5 & 6: Visuals (35 pts)
    visuals = result.get('visual_types', [])
    
    # Scatter Chart (20 pts)
    if 'scatterChart' in visuals:
        score += 20
        feedback.append("✅ Scatter Chart detected.")
    else:
        feedback.append("❌ Scatter Chart missing.")

    # Treemap (15 pts)
    if 'treemap' in visuals:
        score += 15
        feedback.append("✅ Treemap detected.")
    else:
        feedback.append("❌ Treemap missing.")

    # 3. Final Determination
    passed = score >= 70
    
    return {
        "passed": passed,
        "score": score,
        "feedback": " ".join(feedback)
    }